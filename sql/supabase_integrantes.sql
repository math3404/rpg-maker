-- RPG Maker — estrutura remota da equipe
-- Execute no SQL Editor do SEU projeto Supabase.
-- Esta migracao e idempotente: pode ser executada novamente sem apagar dados.
-- A tabela e acessada pelo Django no servidor usando SUPABASE_SECRET_KEY.
-- Nao crie policies para anon/authenticated: a equipe so pode ser gerenciada
-- pela area administrativa do Django.

begin;

create table if not exists public.integrantes (
    id bigint generated by default as identity primary key,
    nome text not null,
    cargo text not null,
    biografia text not null,
    foto_url text,
    created_at timestamptz not null default now()
);

-- Completa a estrutura quando a tabela ja existia, sem remover registros.
alter table public.integrantes
    add column if not exists nome text,
    add column if not exists cargo text,
    add column if not exists biografia text,
    add column if not exists foto_url text,
    add column if not exists created_at timestamptz not null default now();

-- A aplicacao usa id numerico nas rotas /editar/<id>/ e /excluir/<id>/.
-- Se a tabela preexistente tiver outro tipo de id, revise-o manualmente antes
-- de usar o CRUD; esta migracao nao converte identificadores existentes.

alter table public.integrantes enable row level security;

-- A Secret key e usada apenas no servidor Django. Nao liberar acesso publico.
grant usage on schema public to service_role;
revoke all on table public.integrantes from public, anon, authenticated;
grant select, insert, update, delete on table public.integrantes to service_role;

-- Concede acesso a sequencia de id, caso exista (serial/identity).
do $$
declare
    seq_name text;
begin
    seq_name := pg_get_serial_sequence('public.integrantes', 'id');
    if seq_name is not null then
        execute format('grant usage, select on sequence %s to service_role', seq_name);
    end if;
end
$$;

create index if not exists integrantes_nome_idx
    on public.integrantes (nome);

comment on table public.integrantes is
    'Equipe exibida em Quem Somos e gerenciada pela area administrativa do RPG Maker.';

commit;

-- Verificacao rapida da estrutura (resultado esperado: 6 colunas).
select column_name, data_type, is_nullable
from information_schema.columns
where table_schema = 'public'
  and table_name = 'integrantes'
order by ordinal_position;
